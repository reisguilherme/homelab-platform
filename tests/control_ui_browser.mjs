// Run against control_ui_fixture.mjs only, in a browser console:
// await (await import('/__browser-test.js')).runBrowserChecks()
export async function runBrowserChecks() {
  if (location.origin !== 'http://127.0.0.1:8765') throw new Error('Synthetic loopback fixture required.');
  const passed = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const wait = async (predicate, message) => { const until = Date.now() + 6500; while (!predicate()) { if (Date.now() > until) throw new Error(message); await new Promise(resolve => setTimeout(resolve, 40)); } };
  const visible = node => !!node && !node.closest('[hidden]') && (node.offsetWidth > 0 || node.offsetHeight > 0);
  const find = text => [...(document.getElementById('action-dialog').open ? document.getElementById('action-dialog') : document).querySelectorAll('button')].find(node => visible(node) && node.textContent.trim() === text);
  const click = text => { const node = find(text); check(node && !node.disabled, `Button unavailable: ${text}`); node.click(); };
  const value = (id, text) => { const node = document.getElementById(id) || document.getElementById(`field-${id}`); check(node, `Field absent: ${id}`); node.value = text; node.dispatchEvent(new Event('input', { bubbles: true })); node.dispatchEvent(new Event('change', { bubbles: true })); };
  const fixture = async body => fetch('/__fixture', { method: 'POST', body: JSON.stringify(body) });
  const requests = async () => (await (await fetch('/__fixture')).json()).requests;
  const close = () => document.getElementById('dialog-close').click();
  const dialog = () => document.getElementById('action-dialog');
  const formsError = text => [...document.querySelectorAll('.form-error')].some(node => visible(node) && node.textContent.includes(text));
  if (!document.getElementById('workspace').hidden) document.getElementById('logout').click();
  await wait(() => !document.getElementById('login-screen').hidden, 'Logout before fixture');
  await fixture({ reset: true });
  value('username', 'operador@pve'); value('password', 'fixture-only'); click('Entrar →');
  await wait(() => !document.getElementById('totp-form').hidden, 'TOTP challenge missing');
  check(document.getElementById('workspace').hidden, 'Challenge must not authenticate');
  check(document.getElementById('password').value === '', 'Password remains after challenge');
  value('totp', '12345678'); click('Confirmar acesso');
  await wait(() => !document.getElementById('workspace').hidden && !document.getElementById('refresh').disabled && document.getElementById('overview-content').textContent.includes('125,7 GiB'), 'Overview not loaded');
  check(document.querySelectorAll('[style]').length === 0, 'Inline CSS violates CSP');
  passed.push('Login/TOTP, password clearing, overview and CSP');

  click('＋ Criar máquina'); await wait(() => !!document.getElementById('field-name'), 'Creation form');
  check(dialog().textContent.includes('VM desligada'), 'Hardware-only readiness absent');
  value('name', 'fixture-new'); click('Solicitar criação');
  await wait(() => !dialog().open, 'Creation submit'); click('↳ Atividades 1');
  await wait(() => document.getElementById('operations-content').textContent.includes('Criação · fixture-new'), 'Tracked creation absent');
  check(!document.getElementById('operations-content').textContent.includes('Concluída'), '202 shown as completion');
  const create = (await requests()).find(item => item.method === 'POST' && item.path === '/vms');
  check(create.csrf && create.key?.length >= 16 && create.body.profileId === 'small', 'Creation headers/payload');
  await fixture({ completed: true });
  await wait(() => document.getElementById('operations-content').textContent.includes('Concluída'), 'Task completion not polled');
  passed.push('Creation profile, CSRF/idempotency, 202 pending and confirmed polling');

  click('▤ Máquinas virtuais'); click('mediaserver-fixture');
  await wait(() => !!find('Recursos'), 'VM detail'); click('Recursos');
  check(document.activeElement.textContent === 'Recursos', 'Selected tab lost focus');
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
  await wait(() => !!find('＋ Conceder acesso'), 'Keyboard cannot navigate ACL tab');
  check(document.activeElement.textContent === 'Acessos', 'Arrow key lost focus');
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true }));
  check(!!find('Salvar recursos'), 'Keyboard cannot return to resources');
  passed.push('Tabs keep focus and support arrow-key navigation');
  await fixture({ fault: 'denied' }); click('Salvar recursos');
  await wait(() => formsError('revogada'), '403 must appear in form');
  passed.push('403 shows revoked authorization without optimistic success');
  await fixture({ fault: 'conflict' }); click('Salvar recursos');
  await wait(() => document.getElementById('global-notice').textContent.includes('estado mudou'), '409 conflict must reload');
  await wait(() => !!find('Salvar recursos') && !find('Salvar recursos').disabled, 'Resource form after conflict');
  passed.push('409 refreshes stale VM configuration');

  await fixture({ fault: 'ambiguous' }); click('Salvar recursos');
  await wait(() => document.getElementById('global-notice').textContent.includes('desconhecido'), 'Ambiguous result hidden');
  const before = (await requests()).filter(item => item.method === 'PATCH');
  click('Salvar recursos'); await wait(() => formsError('pendente'), 'Duplicate intent not blocked');
  check((await requests()).filter(item => item.method === 'PATCH').length === before.length, 'Duplicate sent automatically');
  document.querySelector('[data-view="activity"]').click();
  await wait(() => !!find('Conferir / reconciliar a mesma intenção'), 'Reconciliation action absent');
  await fixture({ completed: true }); click('Conferir / reconciliar a mesma intenção');
  await wait(() => !find('Conferir / reconciliar a mesma intenção'), 'Reconciliation still unknown');
  const retries = (await requests()).filter(item => item.method === 'PATCH');
  check(retries.at(-1).key === before.at(-1).key, 'Retry replaced the idempotency key');
  passed.push('503 remains unknown; duplicate blocked; explicit retry preserves idempotency');

  document.querySelector('[data-view="vms"]').click(); click('mediaserver-fixture');
  await wait(() => !!find('Forçar parada'), 'Summary actions'); click('Forçar parada');
  check(find('Forçar parada')?.disabled || !find('Forçar parada'), 'Force stop initially enabled');
  value('power-confirmation', 'wrong-name'); check([...dialog().querySelectorAll('button')].find(node => node.type === 'submit').disabled, 'Wrong force name enabled');
  value('power-confirmation', 'mediaserver-fixture'); check(!dialog().querySelector('button[type=submit]').disabled, 'Exact force name disabled'); close();
  click('Revisar exclusão');
  await wait(() => !!document.getElementById('field-delete-confirmation'), 'Deletion preview');
  value('delete-confirmation', 'mediaserver-fixture '); check(dialog().querySelector('button[type=submit]').disabled, 'Trimmed name accepted');
  value('delete-confirmation', 'mediaserver-fixture'); click('Excluir permanentemente');
  await wait(() => !dialog().open, 'Deletion submission');
  const deletion = (await requests()).find(item => item.method === 'DELETE' && item.path === '/vms/901');
  check(deletion?.body.intentId === 'preview-fixture' && deletion.body.confirmationName === 'mediaserver-fixture', 'Deletion without bound preview');
  passed.push('Force-stop exact name and deletion bound to explicit preview');

  click('Acessos'); await wait(() => !!find('＋ Conceder acesso'), 'ACL loading');
  const revokeButtons = [...document.querySelectorAll('button')].filter(node => visible(node) && node.textContent === 'Revogar');
  check(revokeButtons.length === 3 && revokeButtons[0].disabled && !revokeButtons[1].disabled && revokeButtons[2].disabled, 'Inherited or token ACL is editable');
  check(document.getElementById('detail-tab-content').textContent.includes('Lista parcial') && document.getElementById('detail-tab-content').textContent.includes('Token de API'), 'Partial ACL/token warning absent');
  click('＋ Conceder acesso'); value('principalType', 'group'); click('Conceder acesso');
  await wait(() => !dialog().open, 'ACL grant submit');
  const grant = (await requests()).find(item => item.method === 'PUT' && item.path.endsWith('/acl'));
  check(grant.body.principalType === 'group' && grant.body.expectedAclDigest === 'acl-fixture', 'ACL grant missing kind/digest');
  [...document.querySelectorAll('button')].find(node => visible(node) && node.textContent === 'Revogar' && !node.disabled).click();
  click('Revogar entrada'); await wait(() => !dialog().open, 'ACL revoke submit');
  const revoked = (await requests()).find(item => item.method === 'DELETE' && item.path.endsWith('/acl'));
  check(revoked.body.principal === 'viewer@pve' && revoked.body.expectedAclDigest === 'acl-fixture', 'ACL revoke missing explicit principal/digest');
  passed.push('ACL user/group inputs, inherited protection and differential grant/revoke');
  document.getElementById('logout').click();
  await wait(() => !document.getElementById('login-screen').hidden, 'Logout did not clear UI');
  check(document.getElementById('workspace').hidden && localStorage.length === 0 && sessionStorage.length === 0, 'Session persisted in browser storage');
  passed.push('Logout clears workspace without browser token storage');
  value('username', 'operador@pve'); value('password', 'fixture-only'); click('Entrar →');
  await wait(() => !document.getElementById('totp-form').hidden, 'Second TOTP'); value('totp', '123456'); click('Confirmar acesso');
  await wait(() => !document.getElementById('workspace').hidden && !document.getElementById('refresh').disabled, 'Second session');
  document.querySelector('[data-view="activity"]').click();
  await wait(() => !!find('Acompanhar operação'), 'Audit cannot recover task after login'); click('Acompanhar operação');
  await wait(() => document.getElementById('operations-content').textContent.includes('Operação fixture-'), 'Recovered operation absent');
  passed.push('New session resumes authorized task from audit without resending mutation');
  document.querySelector('[data-view="vms"]').click(); click('mediaserver-fixture');
  await wait(() => !!find('Recursos'), 'Race test VM'); click('Recursos');
  await fixture({ mutationDelay: 1200 }); click('Salvar recursos'); document.getElementById('logout').click();
  await wait(() => !document.getElementById('login-screen').hidden, 'Race logout');
  value('username', 'operador@pve'); value('password', 'fixture-only'); click('Entrar →');
  await wait(() => !document.getElementById('totp-form').hidden, 'Race TOTP'); value('totp', '123456'); click('Confirmar acesso');
  await wait(() => !document.getElementById('workspace').hidden && !document.getElementById('refresh').disabled, 'Race session');
  await new Promise(resolve => setTimeout(resolve, 1500));
  check(document.getElementById('task-count').hidden, 'Late mutation response leaked into another session');
  await fixture({ completed: true });
  passed.push('Late mutation response is discarded after session change');
  return { passed, count: passed.length };
}
